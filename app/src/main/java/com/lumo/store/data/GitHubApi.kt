@Serializable
data class CatalogItem(
    val name: String,
    val id: String = "",
    val description: String = "",
    val icon: String = "",
    val repoUrl: String = "",
    val githubRepo: String = "",
    val category: String = "Utility",
    val author: String = "",
    val packageName: String = "",
    val screenshots: List<String> = emptyList(),
    val downloadUrl: String = ""
)

/**
 * Mirror entry for one app.
 * Generated by GitHub Actions every 6 hours.
 *
 * Format:
 * {
 *   "version": "v1.0.0",
 *   "releaseNotes": "...",
 *   "size": 18234567,
 *   "downloadUrl": "...",
 *   "downloadCount": 12483,           ← NEW
 *   "variants": [                      ← NEW
 *     {
 *       "filename": "app-arm64-v8a.apk",
 *       "arch": "arm64-v8a",
 *       "size": 8500000,
 *       "downloadUrl": "...",
 *       "downloadCount": 10000
 *     }
 *   ]
 * }
 */
@Serializable
data class MirrorEntry(
    val version: String = "",
    val releaseNotes: String = "",
    val size: Long = 0L,
    val downloadUrl: String = "",
    val downloadCount: Long = 0L,                       // ✅ NEW
    val variants: List<MirrorVariant> = emptyList()     // ✅ NEW
)

/**
 * One variant inside a mirror entry.
 * Represents a single APK (arm64, armv7, x86, universal, etc.)
 */
@Serializable
data class MirrorVariant(
    val filename: String = "",
    val arch: String = "universal",
    val size: Long = 0L,
    val downloadUrl: String = "",
    val downloadCount: Long = 0L
)

class RateLimitException(
    val resetTime: String,
    val isUsingDefaultToken: Boolean
) : Exception("Rate limit exceeded. Resets at $resetTime")

object GitHubApi {

    // Leave empty to use anonymous free tier (60/hr)
    // Paste "ghp_..." here for a developer token (5,000/hr)
    private const val DEFAULT_TOKEN = ""

    private val client = HttpClient {
        install(ContentNegotiation) {
            json(Json { ignoreUnknownKeys = true; isLenient = true })
        }
    }

    private val jsonParser = Json { ignoreUnknownKeys = true; isLenient = true }

    // ---------- URL NORMALIZERS ----------

    fun normalizeImageUrl(url: String?): String {
        if (url.isNullOrBlank()) return ""
        var u = url.trim()
        u = u.substringBefore("?")

        u = u.replace(
            Regex("""^https?://(?:www\.)?github\.com/([^/]+)/([^/]+)/blob/(.+)$"""),
            "https://raw.githubusercontent.com/$1/$2/$3"
        )

        u = u.replace(
            Regex("""^https?://(?:www\.)?github\.com/([^/]+)/([^/]+)/raw/(.+)$"""),
            "https://raw.githubusercontent.com/$1/$2/$3"
        )

        return u
    }

    fun normalizeGithubRepo(repo: String?): String {
        if (repo.isNullOrBlank()) return ""
        var r = repo.trim()

        while (r.contains("github.com/github.com/")) {
            r = r.replace("github.com/github.com/", "github.com/")
        }
        while (r.contains("github.com/https://github.com/")) {
            r = r.replace("github.com/https://github.com/", "github.com/")
        }
        while (r.contains("github.com/http://github.com/")) {
            r = r.replace("github.com/http://github.com/", "github.com/")
        }

        r = r.removePrefix("https://github.com/")
        r = r.removePrefix("http://github.com/")
        r = r.removePrefix("https://www.github.com/")
        r = r.removePrefix("http://www.github.com/")
        r = r.removePrefix("www.github.com/")
        r = r.removePrefix("github.com/")

        r = r.substringBefore("/blob/")
        r = r.substringBefore("/tree/")
        r = r.substringBefore("/releases/")
        r = r.substringBefore("/raw/")
        r = r.removeSuffix("/")

        return r
    }

    fun normalizeRepoUrl(url: String?, githubRepo: String?): String {
        if (!url.isNullOrBlank()
            && !url.contains("github.com/https")
            && !url.contains("github.com/http")
            && !url.contains("github.com/github.com")
        ) {
            return url.trim().substringBefore("?").removeSuffix("/")
        }
        val cleanRepo = normalizeGithubRepo(githubRepo)
        return if (cleanRepo.isNotBlank()) "https://github.com/$cleanRepo" else ""
    }

    // ---------- TOKEN + HEADERS ----------

    private fun getEffectiveToken(userToken: String?): String? {
        if (!userToken.isNullOrBlank()) return userToken.trim()
        val d = DEFAULT_TOKEN.trim()
        return when {
            d.isEmpty() -> null
            d.contains("YOUR", ignoreCase = true) -> null
            d.startsWith("ghp_") || d.startsWith("github_pat_") -> d
            else -> null
        }
    }

    private fun HttpRequestBuilder.applyGitHubHeaders(token: String?) {
        header("Accept", "application/vnd.github+json")
        header("User-Agent", "LumoStore-App")
        if (!token.isNullOrBlank()) header("Authorization", "Bearer $token")
    }

    private fun checkRateLimit(
        status: HttpStatusCode,
        headers: io.ktor.http.Headers,
        userToken: String?
    ) {
        val remaining = headers["x-ratelimit-remaining"]?.toIntOrNull() ?: -1
        val isLimit = (status == HttpStatusCode.Forbidden ||
                status == HttpStatusCode.TooManyRequests) && remaining == 0
        if (!isLimit) return

        val reset = headers["x-ratelimit-reset"] ?: ""
        val formatted = try {
            val epoch = reset.toLongOrNull()
            if (epoch != null) java.text.SimpleDateFormat("HH:mm", java.util.Locale.getDefault())
                .format(java.util.Date(epoch * 1000))
            else "जल्द"
        } catch (e: Exception) { "जल्द" }

        throw RateLimitException(
            resetTime = formatted,
            isUsingDefaultToken = userToken.isNullOrBlank()
        )
    }

    private fun HttpStatusCode.isOk(): Boolean = value in 200..299

    private suspend fun tryGet(url: String, token: String?): Pair<HttpResponse, Boolean> {
        val first = client.get(url) { applyGitHubHeaders(token) }
        if (first.status.value == 401 && token != null) {
            val anon = client.get(url) { applyGitHubHeaders(null) }
            return anon to true
        }
        return first to false
    }

    // ---------- API CALLS ----------

    suspend fun fetchMirror(mirrorUrl: String): Map<String, MirrorEntry>? {
        return try {
            val url = "$mirrorUrl?t=${System.currentTimeMillis()}"
            val text = client.get(url) {
                header("User-Agent", "LumoStore-App")
            }.bodyAsText()

            if (text.isBlank() || text.trimStart().startsWith("<")) return null

            val map: Map<String, MirrorEntry> = jsonParser.decodeFromString(text)
            if (map.isEmpty()) null else map
        } catch (e: Exception) {
            android.util.Log.w("LumoStore", "mirror fetch failed: ${e.message}")
            null
        }
    }

    suspend fun getLatestRelease(owner: String, repo: String, userToken: String?): GitHubRelease? {
        val token = getEffectiveToken(userToken)
        val latestUrl = "https://api.github.com/repos/$owner/$repo/releases/latest"

        val (resp, anon1) = tryGet(latestUrl, token)
        checkRateLimit(resp.status, resp.headers, if (anon1) null else userToken)
        if (resp.status.isOk()) {
            return try { resp.body<GitHubRelease>() } catch (e: Exception) { null }
        }

        if (resp.status == HttpStatusCode.NotFound) {
            val listUrl = "https://api.github.com/repos/$owner/$repo/releases"
            val (listResp, anon2) = tryGet(listUrl, token)
            checkRateLimit(listResp.status, listResp.headers, if (anon2) null else userToken)
            if (listResp.status.isOk()) {
                return try {
                    val releases: List<GitHubRelease> = listResp.body()
                    releases.firstOrNull()
                } catch (e: Exception) { null }
            }
        }
        return null
    }

    suspend fun fetchCatalogRaw(url: String): String? {
        return try {
            val timestamp = System.currentTimeMillis()
            client.get("$url?t=$timestamp") {
                header("User-Agent", "LumoStore-App")
            }.bodyAsText()
        } catch (e: Exception) { null }
    }

    // ---------- AUTO-FETCH REPO INFO (for Submit screen) ----------

    @Serializable
    private data class RepoApiData(
        val name: String = "",
        @kotlinx.serialization.SerialName("full_name") val fullName: String = "",
        val description: String? = null,
        val owner: OwnerApiData = OwnerApiData(),
        @kotlinx.serialization.SerialName("html_url") val htmlUrl: String = ""
    )

    @Serializable
    private data class OwnerApiData(
        val login: String = "",
        val name: String? = null
    )

    /**
     * Fetches repo metadata + tries to auto-detect packageName from build.gradle.
     * @param repoUrl Any form of GitHub URL or "owner/repo"
     * @return RepoInfo or null on failure
     */
    suspend fun fetchRepoInfo(repoUrl: String, userToken: String?): RepoInfo? {
        val cleanRepo = normalizeGithubRepo(repoUrl)
        if (!cleanRepo.contains("/")) return null

        val parts = cleanRepo.split("/")
        if (parts.size < 2) return null
        val owner = parts[0]
        val repo = parts[1]

        val token = getEffectiveToken(userToken)

        // 1. Fetch repo metadata
        val repoApiUrl = "https://api.github.com/repos/$owner/$repo"
        val (resp, anon) = tryGet(repoApiUrl, token)
        checkRateLimit(resp.status, resp.headers, if (anon) null else userToken)

        if (!resp.status.isOk()) {
            android.util.Log.w("LumoStore", "fetchRepoInfo: repo not found $owner/$repo")
            return null
        }

        val repoData = try { resp.body<RepoApiData>() } catch (e: Exception) {
            android.util.Log.w("LumoStore", "fetchRepoInfo: parse failed ${e.message}")
            return null
        }

        // 2. Try to find package name from build files
        val packageName = detectPackageName(owner, repo)

        // 3. Try to find an icon in common locations
        val iconUrl = detectIconUrl(owner, repo)

        // 4. Guess category from description/keywords
        val category = guessCategory(repoData.description ?: "", repoData.name)

        return RepoInfo(
            owner = owner,
            repoName = repoData.name.ifBlank { repo },
            githubRepo = "$owner/$repo",
            description = repoData.description?.trim() ?: "",
            authorName = repoData.owner.name?.takeIf { it.isNotBlank() } ?: owner,
            packageName = packageName,
            suggestedIconUrl = iconUrl,
            suggestedCategory = category
        )
    }

    /**
     * Tries to read applicationId from build.gradle / build.gradle.kts.
     * Checks both main and master branches.
     */
    private suspend fun detectPackageName(owner: String, repo: String): String {
        val paths = listOf(
            "app/build.gradle.kts",
            "app/build.gradle",
            "build.gradle.kts",
            "build.gradle"
        )
        val branches = listOf("main", "master")

        for (branch in branches) {
            for (path in paths) {
                val url = "https://raw.githubusercontent.com/$owner/$repo/$branch/$path"
                try {
                    val text = client.get(url) {
                        header("User-Agent", "LumoStore-App")
                    }.bodyAsText()

                    // Kotlin DSL: applicationId = "com.example"
                    val kts = Regex("""applicationId\s*=\s*["']([^"']+)["']""").find(text)
                    if (kts != null) {
                        android.util.Log.d("LumoStore", "package detected: ${kts.groupValues[1]} from $path")
                        return kts.groupValues[1]
                    }

                    // Groovy: applicationId "com.example"
                    val groovy = Regex("""applicationId\s+["']([^"']+)["']""").find(text)
                    if (groovy != null) {
                        android.util.Log.d("LumoStore", "package detected: ${groovy.groupValues[1]} from $path")
                        return groovy.groupValues[1]
                    }
                } catch (_: Exception) {
                    // try next path
                }
            }
        }
        android.util.Log.d("LumoStore", "package: no build.gradle found for $owner/$repo")
        return ""
    }

    /**
     * Tries to guess a working icon URL.
     * Strategy: try GitHub owner avatar (always works) — users can override.
     */
    private fun detectIconUrl(owner: String, repo: String): String {
        // GitHub serves owner avatars at /{owner}.png (reliable, 460x460)
        return "https://github.com/$owner.png"
    }

    /**
     * Guesses category from description keywords.
     */
    private fun guessCategory(description: String, repoName: String): String {
        val text = "$description $repoName".lowercase()
        return when {
            text.contains("game") -> "Games"
            text.contains("music") || text.contains("player") || text.contains("video") ||
                    text.contains("audio") || text.contains("media") -> "Media"
            text.contains("learn") || text.contains("course") || text.contains("study") ||
                    text.contains("education") -> "Educational"
            text.contains("note") || text.contains("todo") || text.contains("task") ||
                    text.contains("calendar") -> "Productivity"
            text.contains("chat") || text.contains("social") || text.contains("message") -> "Social"
            text.contains("tool") || text.contains("utility") -> "Tools"
            text.contains("develop") || text.contains("code") || text.contains("git") -> "Developer"
            else -> "Utility"
        }
    }

    fun parseCatalog(jsonString: String): List<CatalogItem> {
        return try {
            val items: List<CatalogItem> = jsonParser.decodeFromString(jsonString)
            items.map { item ->
                item.copy(
                    icon = normalizeImageUrl(item.icon),
                    screenshots = item.screenshots.map { normalizeImageUrl(it) },
                    githubRepo = normalizeGithubRepo(item.githubRepo),
                    repoUrl = normalizeRepoUrl(item.repoUrl, item.githubRepo)
                )
            }
        } catch (e: Exception) {
            android.util.Log.e("LumoStore", "parseCatalog error: ${e.message}")
            emptyList()
        }
    }
}